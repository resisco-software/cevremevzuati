export type Category = {
  id: string;
  label: string;
  shortLabel: string;
  description: string;
  subtopics: string[];
};

/** Bir kaydın yürürlük durumu. Sitenin iç doğrulama durumu ayrı alanda tutulur. */
export type RecordStatus = 'Yürürlükte' | 'Yürürlükten kaldırıldı';

/**
 * Kaydın site tarafından doğrulanma durumu.
 * - 'doğrulandı': yayım tarihi ve resmî ad, Resmî Gazete günlük indeksinde
 *   birebir teyit edildi ve kaynak bağlantısı madde düzeyinde açılıyor.
 * - 'bekliyor': kayıt eklendi, teyit süreci tamamlanmadı.
 * Bu alan bir yürürlük bilgisi değildir; liste rozetinde gösterilmez.
 */
export type Verification = 'doğrulandı' | 'bekliyor';

export type Legislation = {
  slug: string;
  /** Güncel resmî ad. */
  title: string;
  /** İlk yayımdaki ad, sonradan değiştiyse. */
  originalTitle?: string;
  /** Arama için kısaltma ve halk arasındaki adlar. */
  aliases: string[];
  type: 'Kanun' | 'Yönetmelik' | 'Tebliğ';
  categories: string[];
  /** Tüm tesisleri bağlayan temel düzenleme. */
  foundation?: boolean;
  publicationDate: string;
  publicationLabel: string;
  gazetteNumber: string;
  /** Madde düzeyinde resmî kaynak bağlantısı. */
  sourceUrl: string;
  /** Bağlantı günün tam sayfası içindeki bölüme gidiyorsa açıklama. */
  sourceNote?: string;
  /** mevzuat.gov.tr konsolide (güncel) metin. */
  consolidatedUrl?: string;
  summary: string;
  /** Kimi kapsar: kullanıcının "beni ilgilendirir mi" sorusunun cevabı. */
  appliesTo: string;
  /** Önce bakılacak ek, liste veya madde. */
  primaryAnnex?: string;
  /** Resmî metindeki madde, ek ve tablo başlıklarından oluşan okuma rotası. */
  officialReferences?: Array<{
    reference: string;
    title: string;
  }>;
  /** Tipik yükümlülük başlıkları. */
  obligations: string[];
  status: RecordStatus;
  verification: Verification;
  checkedAt: string;
  changes?: Array<{
    date: string;
    label: string;
    sourceUrl: string;
  }>;
};

