export function getCategory(id: string) {
  return categories.find((category) => category.id === id);
}

export function getLegislation(slug: string) {
  return legislation.find((item) => item.slug === slug);
}

/** Bir alanın doğrudan etiketli kayıt sayısı. Temel düzenleme sayıya eklenmez. */
export function categoryRecordCount(id: string) {
  return legislation.filter(
    (item) =>
      item.status !== 'Yürürlükten kaldırıldı' && item.categories.includes(id),
  ).length;
}

/** Kapsam haritasında görsel ağırlık için en kalabalık alanın kayıt sayısı. */
export function maxCategoryRecordCount() {
  return Math.max(...categories.map((category) => categoryRecordCount(category.id)));
}

/** Tüm alt konu başlıklarının toplamı; prozadaki sayılar bu değerden üretilir. */
export function subtopicCount() {
  return categories.reduce((total, category) => total + category.subtopics.length, 0);
}

const TR_MONTHS = [
  'Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran',
  'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık',
];

function parseTurkishDate(value: string) {
  const [day, month, year] = value.split(' ');
  const monthIndex = TR_MONTHS.indexOf(month);
  if (monthIndex < 0) return 0;
  return Date.UTC(Number(year), monthIndex, Number(day));
}

/**
 * Kayıtlar arasındaki en yeni kontrol tarihi. Altbilgi ve liste başlığı
 * bu değeri kullanır; tarih hiçbir yerde ikinci kez yazılmaz.
 */
export function lastSourceCheck() {
  return legislation
    .map((item) => item.checkedAt)
    .reduce((latest, current) =>
      parseTurkishDate(current) > parseTurkishDate(latest) ? current : latest,
    );
}

/**
 * Aynı Resmî Gazete sayısında yayımlanmış diğer kayıtlar.
 * Altı MET tebliği (33093) ve iki elektronik eşya yönetmeliği (32055) gibi
 * kümelerde "aynı nüsha, ayrı kayıt" ilişkisini görünür kılar.
 */
export function sameGazetteRecords(slug: string) {
  const item = getLegislation(slug);
  if (!item) return [];
  return legislation.filter(
    (candidate) =>
      candidate.slug !== slug &&
      candidate.gazetteNumber === item.gazetteNumber &&
      candidate.publicationDate === item.publicationDate,
  );
}

/** Doğrulama durumu özetleri; yöntem sayfasında gösterilir. */
export function verificationSummary() {
  const verified = legislation.filter((item) => item.verification === 'doğrulandı').length;
  return { verified, pending: legislation.length - verified, total: legislation.length };
}

/**
 * Birincil arama metni: kaydın kimliği.
 * Bir kayıt buradan eşleşirse sonuç listesinin başında gösterilir.
 */
export function primarySearchText(item: Legislation) {
  return [
    item.title,
    item.originalTitle ?? '',
    item.aliases.join(' '),
    item.type,
    item.gazetteNumber,
  ].join(' ');
}

/**
 * İkincil arama metni: kaydın konusu ve kapsamı.
 * Buradan gelen eşleşmeler konu araması sayılır ve listenin sonunda yer alır.
 */
export function secondarySearchText(item: Legislation) {
  const categoryTerms = item.categories
    .flatMap((id) => {
      const entry = categories.find((candidate) => candidate.id === id);
      return entry ? [entry.label, entry.shortLabel, ...entry.subtopics] : [];
    })
    .join(' ');
  return [
    item.summary,
    item.appliesTo,
    item.primaryAnnex ?? '',
    item.obligations.join(' '),
    categoryTerms,
    item.changes?.map((change) => change.label).join(' ') ?? '',
  ].join(' ');
}
